#!/usr/bin/env node
/**
 * Copies the static runtime assets CesiumJS loads at run time (web workers,
 * textures, third-party libraries and widget styles) from the installed
 * `cesium` package into `public/cesium`.
 *
 * Cesium resolves these files over HTTP from `CESIUM_BASE_URL`, so they cannot
 * be bundled. The copy is generated output: it is git-ignored and refreshed by
 * the `postinstall` and `prebuild` scripts.
 */
import { createRequire } from "node:module";
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ASSET_DIRECTORIES = ["Assets", "ThirdParty", "Widgets", "Workers"];

const here = dirname(fileURLToPath(import.meta.url));
const targetRoot = resolve(here, "..", "public", "cesium");

function resolveCesiumBuildDirectory() {
  const require = createRequire(import.meta.url);
  const packageJsonPath = require.resolve("cesium/package.json");
  return join(dirname(packageJsonPath), "Build", "Cesium");
}

async function main() {
  let sourceRoot;
  try {
    sourceRoot = resolveCesiumBuildDirectory();
  } catch {
    console.error(
      "[cesium-assets] The 'cesium' package is not installed. Run pnpm install in app/ first.",
    );
    process.exitCode = 1;
    return;
  }

  await rm(targetRoot, { recursive: true, force: true });
  await mkdir(targetRoot, { recursive: true });

  for (const directory of ASSET_DIRECTORIES) {
    await cp(join(sourceRoot, directory), join(targetRoot, directory), {
      recursive: true,
    });
  }

  await writeFile(
    join(targetRoot, "README.txt"),
    [
      "Generated by app/scripts/copy-cesium-assets.mjs.",
      "Copied from the installed cesium package (Build/Cesium).",
      "Do not edit or commit: this directory is git-ignored.",
      "",
    ].join("\n"),
    "utf8",
  );

  console.log(`[cesium-assets] Copied ${ASSET_DIRECTORIES.join(", ")} to public/cesium.`);
}

await main();
